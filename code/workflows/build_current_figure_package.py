#!/usr/bin/env python3
"""Build or verify the curated manuscript-figure package without rerunning models.

The configuration is the single source of truth for selected figure copies.
It records portable source paths, figure roles, status and generators.  Build
copies only the named PNGs; it never deletes historical figures or modifies
any model output.  Verify checks that curated copies and their sources still
match the saved SHA-256 hashes.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


REQUIRED_COLUMNS = {"asset", "role", "status", "source", "generator"}
REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG = Path(__file__).parent / "configs" / "manuscript_figure_package_2026-11-13.csv"
DEFAULT_OUTPUT = REPO_ROOT / "figures" / "manuscript_current"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def git_commit() -> str | None:
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, check=True,
            capture_output=True, text=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def display_path(path: Path) -> str:
    """Keep generated provenance portable when the configuration is in this checkout."""
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def read_config(path: Path) -> list[dict[str, str]]:
    if not path.is_file():
        raise ValueError(f"Figure-package configuration not found: {path}")
    with path.open(newline="", encoding="utf-8") as source:
        reader = csv.DictReader(source)
        if not reader.fieldnames or not REQUIRED_COLUMNS <= set(reader.fieldnames):
            raise ValueError(f"Configuration must contain: {sorted(REQUIRED_COLUMNS)}")
        rows = list(reader)
    if not rows:
        raise ValueError("Figure-package configuration has no rows")
    seen: set[str] = set()
    for row in rows:
        asset = row["asset"]
        if not asset or Path(asset).name != asset or not asset.lower().endswith(".png"):
            raise ValueError(f"asset must be a plain PNG filename: {asset!r}")
        if asset in seen:
            raise ValueError(f"duplicate asset in configuration: {asset}")
        seen.add(asset)
    return rows


def resolve_source(value: str, data_root: Path | None) -> Path:
    resolved = value.replace("${PROJECT_ROOT}", str(REPO_ROOT))
    if "${URBAN_COOLING_DATA_ROOT}" in resolved:
        if data_root is None:
            raise ValueError(
                "Set URBAN_COOLING_DATA_ROOT or pass --data-root: the selected "
                "figure package includes external project-data outputs."
            )
        resolved = resolved.replace("${URBAN_COOLING_DATA_ROOT}", str(data_root))
    if "${" in resolved:
        raise ValueError(f"Unresolved variable in source path: {value}")
    return Path(resolved).expanduser().resolve()


def package_readme(rows: list[dict[str, str]]) -> str:
    main = [row for row in rows if row["role"].startswith("Main Figure")]
    other = [row for row in rows if row not in main]
    lines = [
        "# Current manuscript figure package",
        "",
        "Generated by `code/workflows/build_current_figure_package.py`; do not edit files here manually.",
        "The source configuration and the generated manifest provide provenance and hashes.",
        "Original versioned outputs remain authoritative and are never modified by this build.",
        "",
        "## Attribution and release boundary",
        "",
        "This package contains rendered summary figures only. It does not contain source, clipped,",
        "scenario or model-input rasters and is not a substitute for the underlying datasets.",
        "Figures derived from UKCEH Land Cover Map 2023 inputs must retain the acknowledgement",
        "**Data owned by UK Centre for Ecology & Hydrology; © Database Right/Copyright UKCEH**",
        "and cite Morton et al. (2024), https://doi.org/10.5285/7727ce7d-531e-4d77-b756-5cc59ff016bd.",
        "WorldPop attribution must also be retained where applicable. See",
        "[`DATA_LICENCE_AND_REDISTRIBUTION.md`](../../DATA_LICENCE_AND_REDISTRIBUTION.md) for the",
        "repository release boundary. This package does not change the release status of raw or",
        "machine-readable derivative data.",
        "",
        "## Main figures",
        "",
        "| Figure | File | Status |",
        "|---|---|---|",
    ]
    for row in main:
        lines.append(f"| {row['role']} | [{row['asset']}]({row['asset']}) | {row['status']} |")
    lines.extend(["", "## Supplementary and sensitivity figures", ""])
    for row in other:
        lines.append(f"- **{row['role']}** — [{row['asset']}]({row['asset']}) ({row['status']})")
    lines.extend([
        "",
        "See [`docs/manuscript/index.md`](../../docs/manuscript/index.md) for the current legends,",
        "Results text and scientific qualifications. The included Extended Data Fig. 1 is the",
        "pre-seasonal comparison version; confirm a cause-specific seasonal replacement before",
        "final submission.",
        "",
    ])
    return "\n".join(lines)


def build(
    rows: list[dict[str, str]], output: Path, data_root: Path | None,
    refresh: bool, config_path: Path,
) -> None:
    output.mkdir(parents=True, exist_ok=True)
    records: list[dict[str, str]] = []
    for row in rows:
        source = resolve_source(row["source"], data_root)
        if not source.is_file():
            raise ValueError(f"Configured source does not exist: {source}")
        destination = output / row["asset"]
        source_hash = sha256(source)
        if destination.exists() and sha256(destination) != source_hash:
            if not refresh:
                raise ValueError(
                    f"Existing curated file differs from its source: {destination}. "
                    "Use --refresh only after reviewing the new source output."
                )
        if not destination.exists() or sha256(destination) != source_hash:
            shutil.copy2(source, destination)
        records.append({
            **row,
            "source_sha256": source_hash,
            "curated_sha256": sha256(destination),
        })

    fields = ["asset", "role", "status", "source", "generator", "source_sha256", "curated_sha256"]
    with (output / "manifest.csv").open("w", newline="", encoding="utf-8") as target:
        writer = csv.DictWriter(target, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(records)
    metadata = {
        "schema_version": 1,
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "generator": str(Path(__file__).relative_to(REPO_ROOT)),
        "generator_commit": git_commit(),
        "configuration": {
            "path": display_path(config_path),
            "sha256": sha256(config_path),
        },
        "assets": records,
    }
    (output / "manifest.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    (output / "readme.md").write_text(package_readme(rows), encoding="utf-8")
    print(f"Built and verified {len(records)} curated figures in {output}")


def verify(rows: list[dict[str, str]], output: Path, data_root: Path | None) -> None:
    manifest_path = output / "manifest.csv"
    if not manifest_path.is_file():
        raise ValueError(f"Package manifest is missing: {manifest_path}. Run the build first.")
    with manifest_path.open(newline="", encoding="utf-8") as source:
        saved = {row["asset"]: row for row in csv.DictReader(source)}
    expected = {row["asset"] for row in rows}
    if set(saved) != expected:
        raise ValueError("Package manifest assets do not match the configured selected figures")
    for row in rows:
        asset = row["asset"]
        source = resolve_source(row["source"], data_root)
        destination = output / asset
        if not source.is_file() or not destination.is_file():
            raise ValueError(f"Missing source or curated file for {asset}")
        source_hash, destination_hash = sha256(source), sha256(destination)
        saved_row = saved[asset]
        for field in ("role", "status", "source", "generator"):
            if saved_row.get(field) != row[field]:
                raise ValueError(f"Manifest metadata is stale for {asset}; rerun the build after review")
        if source_hash != destination_hash:
            raise ValueError(f"Curated copy differs from source: {asset}")
        if saved_row.get("source_sha256") != source_hash or saved_row.get("curated_sha256") != destination_hash:
            raise ValueError(f"Manifest hash is stale for {asset}; rerun the build after review")
    print(f"Verified {len(rows)} curated figures, sources and saved hashes in {output}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--data-root", type=Path, default=os.environ.get("URBAN_COOLING_DATA_ROOT"))
    parser.add_argument("--verify", action="store_true", help="Verify only; do not copy or write files")
    parser.add_argument("--refresh", action="store_true", help="Replace a curated PNG only when its reviewed source changed")
    args = parser.parse_args()
    try:
        config = args.config.expanduser().resolve()
        rows = read_config(config)
        data_root = args.data_root.expanduser().resolve() if args.data_root else None
        if data_root is not None and not data_root.is_dir():
            raise ValueError(f"Data root not found: {data_root}")
        output = args.output.expanduser().resolve()
        if args.verify:
            verify(rows, output, data_root)
        else:
            build(rows, output, data_root, args.refresh, config)
    except ValueError as error:
        parser.error(str(error))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
